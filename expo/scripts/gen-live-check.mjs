#!/usr/bin/env node
/**
 * Writes supabase/check-tryal-friends-live.sql: ONE read-only SELECT for the Supabase SQL editor that says, per function defined in
 * supabase/migration-tryal-friends.sql, whether the live database holds exactly that file's version ("match"), a different one
 * ("MISMATCH") or none ("MISSING"). It compares md5 of the function body (pg_proc.prosrc, which is the text between the $$ marks in the
 * file, byte for byte) with the md5 of the body in the file, so it does not depend on the Postgres version or on formatting.
 * Scope: functions only (not policies, triggers or tables). After Money's migration is applied, chat_check_stranger and chat_messages_guard
 * legitimately differ (marked "-- MONEY" copies; scripts/test-migration-order.mjs keeps them in step).
 *   node scripts/gen-live-check.mjs          (rewrites the .sql file)
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const SRC = new URL("../supabase/migration-tryal-friends.sql", import.meta.url);
const OUT = new URL("../supabase/check-tryal-friends-live.sql", import.meta.url);

export function functionsIn(sql) {
  const out = new Map();
  const re = /create\s+or\s+replace\s+function\s+public\.([a-z_0-9]+)\s*\(/gi;
  let m;
  while ((m = re.exec(sql))) {
    const rest = sql.slice(m.index);
    const b = /\bas\s+(\$[a-z_]*\$)/i.exec(rest);
    if (!b) continue;
    const tag = b[1];
    const bodyStart = b.index + b[0].length;
    const bodyEnd = rest.indexOf(tag, bodyStart);
    const body = rest.slice(bodyStart, bodyEnd);
    out.set(m[1].toLowerCase(), createHash("md5").update(body, "utf8").digest("hex"));   // the last definition in the file wins
  }
  return out;
}

export function buildQuery(sql) {
  const fns = [...functionsIn(sql)].sort(([a], [b]) => a.localeCompare(b));
  const values = fns.map(([n, h]) => `    ('${n}', '${h}')`).join(",\n");
  return `-- READ-ONLY: changes nothing. Paste into the Supabase SQL editor and run.
-- Compares the live functions with supabase/migration-tryal-friends.sql (${fns.length} functions) by the md5 of their bodies.
--   match     the live function is exactly the file's version
--   MISMATCH  a function with that name exists but its body differs (an older or edited version is live)
--   MISSING   no function with that name
-- (Generated by scripts/gen-live-check.mjs from the file; regenerate it if the migration changes.)
with expected(fn, body_md5) as (
  values
${values}
)
select e.fn as function_name,
       case when not exists (select 1 from pg_proc p where p.pronamespace = 'public'::regnamespace and p.proname = e.fn) then 'MISSING'
            when exists (select 1 from pg_proc p where p.pronamespace = 'public'::regnamespace and p.proname = e.fn and md5(p.prosrc) = e.body_md5) then 'match'
            else 'MISMATCH' end as status
from expected e
order by (case when exists (select 1 from pg_proc p where p.pronamespace = 'public'::regnamespace and p.proname = e.fn and md5(p.prosrc) = e.body_md5) then 1 else 0 end), e.fn;
`;
}

if (process.argv[1] && new URL(`file://${process.argv[1]}`).pathname === new URL(import.meta.url).pathname) {
  const q = buildQuery(readFileSync(SRC, "utf8"));
  writeFileSync(OUT, q);
  console.log(`wrote supabase/check-tryal-friends-live.sql (${functionsIn(readFileSync(SRC, "utf8")).size} functions)`);
}
