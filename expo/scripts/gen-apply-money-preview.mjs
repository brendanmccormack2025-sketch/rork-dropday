#!/usr/bin/env node
/**
 * Builds supabase/apply-money-preview.sql: the five Money-preview migrations in order, then ONE combined check query, for pasting into the Supabase
 * SQL editor (no terminal needed). The file is generated, never edited by hand: scripts/test-money-footage-sql.mjs fails if it is stale.
 *   node scripts/gen-apply-money-preview.mjs          (writes the file)
 *   node scripts/gen-apply-money-preview.mjs --check  (exit 1 if the file is out of date)
 */
import { readFileSync, writeFileSync } from "node:fs";

export const PARTS = ["migration-post-links.sql", "migration-money.sql", "migration-money-board.sql", "migration-money-footage.sql", "migration-money-segments.sql"];
const dir = new URL("../supabase/", import.meta.url);
const read = (f) => readFileSync(new URL(f, dir), "utf8").replace(/\r\n/g, "\n");
const noComments = (s) => s.replace(/^\s*--.*$/gm, "").trim().replace(/;\s*$/, "");

export function build() {
  const parts = PARTS.map((f) => `-- ══════════════════════════════════════════════════════════════════════════════\n-- PART: ${f}\n-- ══════════════════════════════════════════════════════════════════════════════\n${read(f).replace(/\s+$/, "")}\n`);
  const footage = noComments(read("check-money-footage.sql"));
  const step2 = noComments(read("check-money-step2-functions.sql"));
  const checks = `-- ══════════════════════════════════════════════════════════════════════════════
-- CHECKS (read-only): one table. Every row should say ok (or info). Anything else says what to do.
-- ══════════════════════════════════════════════════════════════════════════════
select src, check_name, status, detail from (
  select 'footage' as src, check_name, status, detail, 1 as o1 from (
${footage}
  ) f
  union all
  select 'functions', check_name, status, trim(coalesce(used_by, '') || ' ' || coalesce(arguments, '')), 2 from (
${step2}
  ) g
) c
order by (status in ('ok', 'info')), o1, check_name;
`;
  const head = `-- Tryal Money PREVIEW: everything to test the Money tab with campaign footage, in ONE paste for the Supabase SQL editor.
-- GENERATED by expo/scripts/gen-apply-money-preview.mjs from the five migration files below: do not edit by hand.
--
-- Safe to run once, and again (every statement is idempotent). It does NOT run the birthdate lock-down (migration-money.sql only defines it).
-- It re-runs migration-money.sql and migration-money-board.sql in the right order, so it is also safe on a database that already has them:
-- the board file comes after the money file and puts the newer functions back. Do not paste migration-money.sql on its own afterwards.
-- Order: 1 post links, 2 money (flag, adult check), 3 money board (campaigns and rules), 4 money footage (uploads), 5 money segments (long videos in 1-minute parts).
-- Runs as one script; if any statement fails nothing of this paste is kept, and the error names the line.
-- The check table at the end is the result you see.
`;
  return `${head}\n${parts.join("\n")}\n${checks}`;
}

if (process.argv[1] && new URL(import.meta.url).pathname === process.argv[1]) {
  const out = new URL("apply-money-preview.sql", dir);
  const text = build();
  if (process.argv.includes("--check")) {
    let cur = ""; try { cur = readFileSync(out, "utf8"); } catch { /* missing */ }
    if (cur !== text) { console.error("supabase/apply-money-preview.sql is out of date: run node scripts/gen-apply-money-preview.mjs"); process.exit(1); }
    console.log("up to date");
  } else { writeFileSync(out, text); console.log(`wrote ${out.pathname} (${Buffer.byteLength(text)} bytes)`); }
}
